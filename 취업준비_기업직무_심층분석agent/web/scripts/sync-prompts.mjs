import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const sourceDir = join(here, "..", "..", ".cursor", "agents");
const outFile = join(here, "..", "lib", "prompts.generated.ts");

// Vercel may build with only web/ checked out; the committed output is then used as-is.
if (!existsSync(sourceDir)) {
  if (existsSync(outFile)) {
    console.log(`[sync-prompts] ${sourceDir} not found, keeping existing prompts.generated.ts`);
    process.exit(0);
  }
  console.error(`[sync-prompts] ${sourceDir} not found and no generated file exists`);
  process.exit(1);
}

const prompts = {};
for (const file of readdirSync(sourceDir).filter((f) => f.endsWith(".md")).sort()) {
  const raw = readFileSync(join(sourceDir, file), "utf8");
  const match = raw.match(/^---\n([\s\S]*?)\n---\n([\s\S]*)$/);
  if (!match) throw new Error(`[sync-prompts] ${file} has no YAML frontmatter`);
  const name = match[1].match(/^name:\s*(.+)$/m)?.[1].trim();
  if (!name) throw new Error(`[sync-prompts] ${file} has no name field`);
  prompts[name] = match[2].trim();
}

const body =
  "// Generated by scripts/sync-prompts.mjs from .cursor/agents/*.md. Do not edit by hand.\n" +
  `export const AGENT_PROMPTS = ${JSON.stringify(prompts, null, 2)} as const;\n\n` +
  "export type AgentName = keyof typeof AGENT_PROMPTS;\n";

writeFileSync(outFile, body);
console.log(`[sync-prompts] wrote ${Object.keys(prompts).length} prompts to lib/prompts.generated.ts`);
